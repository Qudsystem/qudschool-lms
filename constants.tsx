// UserAvatar Component
export const UserAvatar: React.FC<{
    initial: string;
    imageUrl?: string;
    size?: 'sm' | 'md' | 'lg';
    className?: string;
}> = ({ initial, imageUrl, size = 'md', className = '' }) => {
    const sizeClasses = {
      sm: 'w-8 h-8 text-sm',
      md: 'w-10 h-10 text-base',
      lg: 'w-16 h-16 text-xl',
    };
    return (
      <div className={`relative inline-flex items-center justify-center overflow-hidden bg-primary-light text-primary-dark rounded-full ${sizeClasses[size]} ${className}`}>
        {imageUrl ? (
          <img
            src={imageUrl}
            alt=""
            className="w-full h-full object-cover"
            loading="lazy"
            onError={(event) => {
              event.currentTarget.style.display = 'none';
              const fallback = event.currentTarget.parentElement?.querySelector('span');
              fallback?.classList.remove('opacity-0');
            }}
          />
        ) : null}
        <span className={`font-semibold ${imageUrl ? 'absolute opacity-0' : ''}`}>{initial}</span>
      </div>
    );
};

